#!/usr/bin/env node
/**
 * Writes public/firebase-messaging-sw.js from NEXT_PUBLIC_FIREBASE_* env.
 * Keeps the Firebase web API key out of git; App Hosting injects it at build.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outPath = join(root, "public", "firebase-messaging-sw.js");

/** Load KEY=VALUE lines into process.env without overriding existing values. */
function loadEnvFile(filePath) {
  if (!existsSync(filePath)) return;
  for (const line of readFileSync(filePath, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = value;
  }
}

loadEnvFile(join(root, ".env.local"));
loadEnvFile(join(root, ".env"));


const apiKey =
  process.env.NEXT_PUBLIC_FIREBASE_API_KEY || "YOUR_FIREBASE_WEB_API_KEY";
const authDomain =
  process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN ||
  "every-insurance.firebaseapp.com";
const projectId =
  process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || "every-insurance";
const storageBucket =
  process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET ||
  "every-insurance.firebasestorage.app";
const messagingSenderId =
  process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID || "978334689853";
const appId =
  process.env.NEXT_PUBLIC_FIREBASE_APP_ID ||
  "1:978334689853:web:bf2108057fa442617d1854";

const contents = `/* Generated by scripts/generate-firebase-messaging-sw.mjs — do not edit. */
importScripts(
  "https://www.gstatic.com/firebasejs/11.6.0/firebase-app-compat.js",
);
importScripts(
  "https://www.gstatic.com/firebasejs/11.6.0/firebase-messaging-compat.js",
);

firebase.initializeApp({
  apiKey: ${JSON.stringify(apiKey)},
  authDomain: ${JSON.stringify(authDomain)},
  projectId: ${JSON.stringify(projectId)},
  storageBucket: ${JSON.stringify(storageBucket)},
  messagingSenderId: ${JSON.stringify(messagingSenderId)},
  appId: ${JSON.stringify(appId)},
});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  const title = payload.notification?.title || payload.data?.title || "Pulse";
  const body = payload.notification?.body || payload.data?.body || "";
  const href = payload.data?.href || "/notifications";
  return self.registration.showNotification(title, {
    body,
    data: { href, ...(payload.data || {}) },
  });
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const raw = event.notification?.data?.href || "/notifications";
  let target;
  try {
    if (typeof raw === "string" && raw.startsWith("/")) {
      target = new URL(raw, self.location.origin).href;
    } else {
      const parsed = new URL(String(raw), self.location.origin);
      // Only same-origin destinations — blocks open-redirect phishing via FCM.
      if (parsed.origin !== self.location.origin) {
        target = new URL("/notifications", self.location.origin).href;
      } else {
        target = parsed.href;
      }
    }
  } catch {
    target = new URL("/notifications", self.location.origin).href;
  }
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then(
      (clientList) => {
        for (const client of clientList) {
          if ("focus" in client) {
            client.focus();
            if ("navigate" in client) {
              return client.navigate(target);
            }
            return undefined;
          }
        }
        if (self.clients.openWindow) {
          return self.clients.openWindow(target);
        }
        return undefined;
      },
    ),
  );
});
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, contents);
console.log(`Wrote ${outPath}`);
